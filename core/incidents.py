"""The simulated-incident corpus (benchmarks/incidents/) and its deterministic scorer.

The corpus is SYNTHETIC and generated by scripts/gen_incidents.py; this module only reads
it. `load_bundle(incident_id)` returns the incident's sources as an `EvidenceBundle`: the
source ids are the file paths inside the incident directory (`ticket.md`, `runbook.md`,
`deploy.diff`, `metrics.csv`, `logs/<file>`), lines are 1-based, and every file is checked
against the sha256 in manifest.json first. The ground truth is never part of the bundle.

`score(claims, truth, category=...)` scores a diagnosis with no model, using
`rookwise.evidence`:

- `citation_verified_rate`: valid citations over all citations (`evidence.verify`).
- `evidence_recall`: essential evidence refs that at least one valid citation covers, over
  all essential refs. A valid citation covers a ref when one occurrence of its quote, inside
  its cited lines, falls on a line of the ref. A wide line range whose quote comes from
  another line covers nothing.
- `diagnosis_correct`: the category equals the ground truth's AND at least one essential
  ref is covered. This rule is a proposal (docs/ARCHITECTURE.md, "Benchmark design").
"""

from __future__ import annotations

import hashlib
import json
from collections.abc import Sequence
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from rookwise.evidence import (
    Citation,
    Claim,
    EvidenceBundle,
    EvidenceReport,
    check_citation,
    split_lines,
    verify,
)

REPO_ROOT = Path(__file__).resolve().parents[1]
INCIDENTS_DIR = REPO_ROOT / "benchmarks" / "incidents"
CATEGORIES = (
    "bad_config",
    "code_regression",
    "resource_leak",
    "certificate_expiry",
    "capacity_exhaustion",
    "dependency_latency",
    "disk_exhaustion",
    "network_failure",
)
Category = Literal[
    "bad_config",
    "code_regression",
    "resource_leak",
    "certificate_expiry",
    "capacity_exhaustion",
    "dependency_latency",
    "disk_exhaustion",
    "network_failure",
]


class _Model(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class EvidenceRef(_Model):
    """A citation into the corpus with a note on why it matters."""

    source_id: str
    line_start: int = Field(ge=1)
    line_end: int = Field(ge=1)
    quote: str = Field(min_length=1)
    note: str

    def citation(self) -> Citation:
        return Citation(
            source_id=self.source_id,
            line_start=self.line_start,
            line_end=self.line_end,
            quote=self.quote,
        )


class SourceInfo(_Model):
    lines: int
    committed: bool


class GroundTruth(_Model):
    synthetic: Literal[True]
    note: str
    incident_id: str
    split: Literal["dev", "test"]
    difficulty: Literal["easy", "medium", "hard"]
    root_cause: str
    root_cause_category: Category
    categories: list[str]
    essential_evidence: list[EvidenceRef] = Field(min_length=1)
    supporting_evidence: list[EvidenceRef]
    decoys: list[EvidenceRef] = Field(min_length=2)
    acceptable_remediations: list[str] = Field(min_length=1)
    keyword_free_evidence: bool
    cause_in_deploy_diff: bool
    misleading_first_hypothesis: str | None
    sources: dict[str, SourceInfo]
    log_lines: int
    seed: int


def _manifest(root: Path) -> dict[str, dict[str, object]]:
    return json.loads((root / "manifest.json").read_text(encoding="utf-8"))["files"]


def incident_ids(root: Path = INCIDENTS_DIR) -> list[str]:
    return sorted({path.split("/", 1)[0] for path in _manifest(root)})


def load_ground_truth(incident_id: str, root: Path = INCIDENTS_DIR) -> GroundTruth:
    text = (root / incident_id / "ground_truth.json").read_text(encoding="utf-8")
    return GroundTruth.model_validate_json(text)


def load_bundle(incident_id: str, root: Path = INCIDENTS_DIR) -> EvidenceBundle:
    """Every source of one incident, checked against manifest.json. The logs are not
    committed: rebuild them with `python scripts/gen_incidents.py` when they are missing."""
    prefix = f"{incident_id}/"
    files = {p: info for p, info in _manifest(root).items() if p.startswith(prefix)}
    if not files:
        raise KeyError(f"no incident {incident_id} in {root / 'manifest.json'}")
    sources: dict[str, str] = {}
    for path, info in sorted(files.items()):
        source_id = path[len(prefix) :]
        if source_id == "ground_truth.json":
            continue
        target = root / path
        if not target.exists():
            raise FileNotFoundError(
                f"{target} is missing; rebuild the corpus with `python scripts/gen_incidents.py`"
            )
        data = target.read_bytes()
        if hashlib.sha256(data).hexdigest() != info["sha256"]:
            raise ValueError(f"{path} does not match its sha256 in manifest.json")
        sources[source_id] = data.decode("utf-8")
    return EvidenceBundle(sources=sources)


# -- scoring ---------------------------------------------------------------------------------


class Score(_Model):
    incident_id: str
    category: str | None
    category_correct: bool
    diagnosis_correct: bool
    citation_verified_rate: float
    evidence_recall: float
    essential_covered: list[int]
    evidence: EvidenceReport


def covered_lines(bundle: EvidenceBundle, citation: Citation) -> set[int]:
    """The lines a valid citation's quote falls on (every occurrence inside the cited
    range), with the same whitespace normalization as `rookwise.evidence`. Empty for an
    invalid citation."""
    if check_citation(bundle, citation)[0] != "ok":
        return set()
    lines = split_lines(bundle.sources[citation.source_id])
    words: list[str] = []
    spans: list[tuple[int, int, int]] = []  # (first char, end char, line number)
    position = 0
    for number in range(citation.line_start, citation.line_end + 1):
        line_words = lines[number - 1].split()
        if not line_words:
            continue
        if words:
            position += 1  # the single space that joins two lines
        text = " ".join(line_words)
        spans.append((position, position + len(text), number))
        words.extend(line_words)
        position += len(text)
    joined = " ".join(words)
    quote = " ".join(citation.quote.split())
    found: set[int] = set()
    start = joined.find(quote)
    while start != -1:
        end = start + len(quote)
        found |= {number for first, last, number in spans if first < end and start < last}
        start = joined.find(quote, start + 1)
    return found


def score(
    claims: Sequence[Claim],
    truth: GroundTruth,
    *,
    category: str | None,
    bundle: EvidenceBundle | None = None,
    root: Path = INCIDENTS_DIR,
) -> Score:
    """Score a diagnosis (its category and its claims) against the ground truth."""
    bundle = bundle if bundle is not None else load_bundle(truth.incident_id, root)
    report = verify(bundle, claims)
    covered: dict[str, set[int]] = {}
    for claim in claims:
        for citation in claim.citations:
            lines = covered_lines(bundle, citation)
            if lines:
                covered.setdefault(citation.source_id, set()).update(lines)
    essential_covered = [
        index
        for index, ref in enumerate(truth.essential_evidence)
        if covered.get(ref.source_id, set()) & set(range(ref.line_start, ref.line_end + 1))
    ]
    category_correct = category == truth.root_cause_category
    return Score(
        incident_id=truth.incident_id,
        category=category,
        category_correct=category_correct,
        diagnosis_correct=category_correct and bool(essential_covered),
        citation_verified_rate=report.citation_verified_rate,
        evidence_recall=len(essential_covered) / len(truth.essential_evidence),
        essential_covered=essential_covered,
        evidence=report,
    )
