"""Write the benchmark results as one JSON file, and optionally print a README table.

Reads the run files in benchmarks/results/runs/ (the same loader and aggregation as
verify_benchmark.py) and writes release/out/results.json:

- `runs`: one entry per run file, with its identifiers, outcome, scores, coverage, cost
  and wall time;
- `aggregates`: one entry per (split, configuration), test split first, with the run
  count, the correct count, mean evidence recall, mean coverage, total and mean spent USD
  (six-decimal strings) and total wall time.

With --markdown it also prints a README-ready table: Configuration, Split, Correct (n of
3), Evidence recall, Coverage, Real cost per run (USD), rows ordered (a) hierarchy,
(b) single Ultra, (c) single Lightning, test rows first. Rates and costs are rounded half
up to 3 decimals.

release/out/ is output only; keep it out of git.

Usage:
    python release/results_json.py
    python release/results_json.py --markdown
    python release/results_json.py --results-dir PATH --out PATH
"""

from __future__ import annotations

import argparse
import json
import sys
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

from verify_benchmark import RESULTS_DIR, Aggregate, Run, aggregate, load_runs

OUT_PATH = Path(__file__).resolve().parent / "out" / "results.json"
LABELS = {"a": "(a) hierarchy", "b": "(b) single Ultra", "c": "(c) single Lightning"}
SPLIT_ORDER = ("test", "dev")
CONFIG_ORDER = ("a", "b", "c")
SIX = Decimal("0.000001")


def three(value: float | Decimal) -> str:
    """Half-up rounding to 3 decimals on the decimal text, so 0.7055 gives 0.706."""
    return str(Decimal(str(value)).quantize(Decimal("0.001"), rounding=ROUND_HALF_UP))


def order(split: str, configuration: str) -> tuple[int, int, str, str]:
    """Test split first, then (a), (b), (c); unknown values last."""
    s = SPLIT_ORDER.index(split) if split in SPLIT_ORDER else len(SPLIT_ORDER)
    c = CONFIG_ORDER.index(configuration) if configuration in CONFIG_ORDER else 99
    return (s, c, split, configuration)


def run_entry(run: Run) -> dict:
    data = run.raw
    score = data.get("score", {})
    return {
        "file": run.name,
        "incident_id": run.incident_id,
        "split": run.split,
        "configuration": run.configuration,
        "label": LABELS.get(run.configuration, run.configuration),
        "repeat": run.repeat,
        "commit": run.commit,
        "dirty": run.dirty,
        "status": data.get("status"),
        "partial": data.get("partial"),
        "diagnosis_status": data.get("diagnosis_status"),
        "diagnosis_category": data.get("diagnosis_category"),
        "diagnosis_correct": run.diagnosis_correct,
        "category_correct": run.category_correct,
        "evidence_recall": run.evidence_recall,
        "citation_verified_rate": score.get("citation_verified_rate"),
        "citation_first_pass_validity": score.get("citation_first_pass_validity"),
        "coverage": run.coverage,
        "slices_read": data.get("coverage", {}).get("slices_read"),
        "slices_total": data.get("coverage", {}).get("slices_total"),
        "cap_usd": str(run.cap_usd.quantize(SIX)),
        "spent_usd": str(run.spent_usd.quantize(SIX)),
        "wall_clock_s": run.wall_clock_s,
    }


def aggregate_entry(item: Aggregate) -> dict:
    return {
        "split": item.split,
        "configuration": item.configuration,
        "label": LABELS.get(item.configuration, item.configuration),
        "runs": item.runs,
        "diagnosis_correct": item.correct,
        "evidence_recall_mean": item.evidence_recall_mean,
        "coverage_mean": item.coverage_mean,
        "spent_usd_total": str(item.spent_usd_total.quantize(SIX)),
        "spent_usd_mean": str(item.spent_usd_mean.quantize(SIX)),
        "wall_clock_s_total": round(item.wall_clock_s_total, 2),
        "commits": item.commits,
    }


def build(runs: list[Run]) -> dict:
    aggregates = sorted(aggregate(runs), key=lambda a: order(a.split, a.configuration))
    entries = sorted(
        runs, key=lambda r: (*order(r.split, r.configuration), r.incident_id, r.repeat)
    )
    return {
        "note": "Synthetic incidents. Generated by release/results_json.py from the run files.",
        "runs": [run_entry(r) for r in entries],
        "aggregates": [aggregate_entry(a) for a in aggregates],
    }


def markdown_table(results: dict) -> str:
    lines = [
        "| Configuration | Split | Correct (n of 3) | Evidence recall | Coverage "
        "| Real cost per run (USD) |",
        "|---|---|---|---|---|---|",
    ]
    for item in results["aggregates"]:
        lines.append(
            f"| {item['label']} | {item['split']} "
            f"| {item['diagnosis_correct']} of {item['runs']} "
            f"| {three(item['evidence_recall_mean'])} | {three(item['coverage_mean'])} "
            f"| {three(Decimal(item['spent_usd_mean']))} |"
        )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--results-dir", type=Path, default=RESULTS_DIR, help="folder that holds runs/"
    )
    parser.add_argument("--out", type=Path, default=OUT_PATH, help="JSON file to write")
    parser.add_argument("--markdown", action="store_true", help="print the README table")
    args = parser.parse_args(argv)
    runs = load_runs(args.results_dir.resolve() / "runs")
    if not runs:
        print(f"no run files in {args.results_dir / 'runs'}", file=sys.stderr)
        return 1
    results = build(runs)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {args.out} ({len(results['runs'])} runs, {len(results['aggregates'])} groups)")
    if args.markdown:
        print()
        print(markdown_table(results))
    return 0


if __name__ == "__main__":
    sys.exit(main())
