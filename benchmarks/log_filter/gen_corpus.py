def _hex(rng: random.Random, n: int = 8) -> str:
    return "".join(rng.choice("0123456789abcdef") for _ in range(n))


def _latency(rng: random.Random) -> int:
    return max(3, int(rng.lognormvariate(3.7, 0.6)))


def _path(rng: random.Random) -> str:
    return rng.choice(PATHS_GET).format(
        n=rng.randint(10000, 99999), w=rng.choice(WORDS), p=rng.randint(1, 6), h=_hex(rng, 6)
    )


class Noise:
    """Stationary background traffic. `state` carries the few counters that must move forward."""

    def __init__(self, rng: random.Random):
        self.rng = rng
        self.config_version = rng.randint(60, 80)
        self.debug = False
        table = [
            (0.715, self.request),
            (0.05, self.client_error),
            (0.04, self.healthcheck),
            (0.02, self.cache),
            (0.03, self.gc),
            (0.015, self.retry),
            (0.025, self.scheduler),
            (0.008, self.unrelated_error),
            (0.025, self.routine_warn),
            (0.003, self.benign_config),
            (0.01, self.slow_ok),
            (0.015, self.db_stats),
            (0.01, self.dns),
            (0.005, self.log_volume),
            (0.005, self.disk),
            (0.005, self.autoscaler),
            (0.005, self.tls),
            (0.004, self.jvm_mem),
        ]
        self.kinds = [f for _, f in table]
        self.weights = [w for w, _ in table]

    def next(self) -> Event:
        if self.debug and self.rng.random() < 0.35:
            return self.debug_line()
        return self.rng.choices(self.kinds, self.weights)[0]()

    def request(self) -> Event:
        r = self.rng
        if r.random() < 0.8:
            method, path, status = "GET", _path(r), r.choice([200] * 12 + [304])
        else:
            method, path, status = "POST", r.choice(PATHS_POST), r.choice([200, 201, 201, 204])
        return Event(
            "INFO",
            "http",
            f"{method} {path}",
            {
                "status": status,
                "latency_ms": _latency(r),
                "db_queries": r.randint(1, 14),
                "req_id": _hex(r),
            },
        )

    def client_error(self) -> Event:
        r = self.rng
        status = r.choice([404, 404, 401, 422, 429])
        if status == 429:
            return Event(
                "WARN",
                "ratelimit",
                "rate limited client",
                {"client_id": r.choice(CLIENTS), "limit_per_min": 600, "req_id": _hex(r)},
            )
        return Event(
            "INFO",
            "http",
            f"GET {_path(r)}",
            {
                "status": status,
                "latency_ms": _latency(r) // 3 + 2,
                "db_queries": r.randint(0, 2),
                "req_id": _hex(r),
            },
        )

    def healthcheck(self) -> Event:
        return Event("INFO", "health", "healthcheck ok", {"latency_ms": self.rng.randint(2, 6)})

    def cache(self) -> Event:
        miss = round(self.rng.uniform(0.06, 0.24), 2)
        if miss > 0.20:
            return Event(
                "WARN",
                "cache",
                "cache miss_rate above soft threshold 0.20",
                {"miss_rate": miss, "cache": "product"},
            )
        return Event(
            "INFO",
            "cache",
            "cache.stats",
            {
                "cache": "product",
                "hit_ratio": round(1 - miss, 2),
                "entries": self.rng.randint(40000, 52000),
            },
        )

    def gc(self) -> Event:
        pause = int(self.rng.lognormvariate(4.3, 0.6))
        if pause > 500:
            return Event("WARN", "jvm", "long gc pause", {"pause_ms": pause})
        return Event(
            "INFO",
            "jvm",
            "gc pause",
            {"pause_ms": pause, "heap_used_mb": self.rng.randint(900, 1650)},
        )

    def retry(self) -> Event:
        r = self.rng
        return Event(
            "WARN",
            "httpclient",
            "retrying call",
            {
                "upstream": r.choice(["inventory-svc", "pricing-svc", "search-svc"]),
                "attempt": "1/3",
                "reason": r.choice(
                    ["connection reset by peer", "read timeout 800ms", "503 from upstream"]
                ),
                "req_id": _hex(r),
            },
        )

    def scheduler(self) -> Event:
        r = self.rng
        job = r.choice(
            [
                "sitemap-refresh",
                "abandoned-cart-mailer",
                "search-reindex-delta",
                "price-sync",
                "session-gc",
            ]
        )
        if r.random() < 0.5:
            return Event("INFO", "scheduler", "job started", {"name": job})
        return Event(
            "INFO", "scheduler", "job finished", {"name": job, "duration_ms": r.randint(200, 9000)}
        )

    def unrelated_error(self) -> Event:
        r = self.rng
        pick = r.randint(0, 3)
        if pick == 0:
            return Event(
                "ERROR",
                "mail",
                "smtp send failed, will retry",
                {"code": 421, "reply": "service not available", "message_id": _hex(r, 12)},
            )
        if pick == 1:
            return Event(
                "ERROR",
                "webhook",
                "inbound webhook signature invalid",
                {"source": "partner-feed", "delivery_id": _hex(r)},
            )
        if pick == 2:
            return Event(
                "ERROR",
                "images",
                "image resize failed",
                {"reason": "unsupported format", "upload_id": _hex(r)},
            )
        return Event(
            "ERROR",
            "http",
            "unhandled exception in GET /api/v2/users/me/avatar",
            {"exception": "NullPointerException", "status": 500, "req_id": _hex(r)},
        )

    def routine_warn(self) -> Event:
        r = self.rng
        pick = r.randint(0, 2)
        if pick == 0:
            return Event(
                "WARN",
                "http",
                "client used deprecated API version",
                {"header": "v1", "client_id": r.choice(CLIENTS)},
            )
        if pick == 1:
            return Event(
                "WARN",
                "kafka",
                "consumer lag",
                {
                    "group": "order-events",
                    "partition": r.randint(0, 7),
                    "lag": r.randint(300, 2500),
                },
            )
        return Event(
            "WARN",
            "db.pool",
            "waited for connection",
            {"waited_ms": r.randint(60, 240), "active": r.randint(30, 45), "max": 50},
        )

    def benign_config(self) -> Event:
        r = self.rng
        if r.random() < 0.5:
            self.config_version += 1
            return Event(
                "INFO",
                "deploy.agent",
                "config bundle applied",
                {"config_version": self.config_version, "author": "ci-bot"},
            )
        key, old, new = r.choice(BENIGN_KEYS)
        return Event("INFO", "config", f"config.diff {key}: {old} -> {new}", {})

    def slow_ok(self) -> Event:
        r = self.rng
        return Event(
            "INFO",
            "http",
            f"GET {_path(r)}",
            {
                "status": 200,
                "latency_ms": r.randint(800, 2400),
                "db_queries": r.randint(2, 14),
                "req_id": _hex(r),
            },
        )

    def db_stats(self) -> Event:
        r = self.rng
        return Event(
            "INFO",
            "db",
            "db.stats",
            {
                "db_host": "pg-primary",
                "cpu_pct": r.randint(18, 55),
                "active_queries": r.randint(4, 40),
                "queries_per_s": r.randint(700, 2600),
            },
        )

    def dns(self) -> Event:
        r = self.rng
        return Event(
            "INFO",
            "dns",
            "dns lookup",
            {
                "name": r.choice(
                    ["inventory-svc.internal", "pricing-svc.internal", "pg-primary.internal"]
                ),
                "took_ms": r.randint(1, 4),
            },
        )

    def log_volume(self) -> Event:
        return Event("INFO", "logging", "log volume", {"lines_per_s": self.rng.randint(90, 180)})

    def disk(self) -> Event:
        return Event(
            "INFO",
            "disk",
            "disk usage",
            {
                "mount": self.rng.choice(["/var/log", "/data", "/"]),
                "used_pct": self.rng.randint(31, 72),
            },
        )

    def autoscaler(self) -> Event:
        return Event(
            "INFO",
            "autoscaler",
            "autoscaler check",
            {"pool": "web", "replicas": 4, "desired": 4, "p95_ms": self.rng.randint(120, 260)},
        )

    def tls(self) -> Event:
        return Event(
            "INFO",
            "tls",
            "tls session resumed",
            {"peer": self.rng.choice(["payments-gw", "inventory-svc", "pricing-svc"])},
        )

    def jvm_mem(self) -> Event:
        return Event(
            "INFO",
            "jvm",
            "memory",
            {"heap_used_mb": self.rng.randint(900, 1650), "heap_max_mb": 4096},
        )

    def debug_line(self) -> Event:
        r = self.rng
        return Event(
            "DEBUG",
            r.choice(["http", "cache", "db", "session"]),
            r.choice(
                [
                    "request headers parsed",
                    "cache lookup",
                    "sql prepared",
                    "session loaded",
                    "response serialized",
                ]
            ),
            {"req_id": _hex(r), "bytes": r.randint(120, 4000)},
        )


