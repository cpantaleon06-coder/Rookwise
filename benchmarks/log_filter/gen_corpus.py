"""Write the SYNTHETIC incident corpus for the stage-0 log filter experiment.

Six incidents of a fictional web service, `harborline-web`: three dev, three test. Every log
starts with a SYNTHETIC header line, mixes healthy traffic, routine warnings, retries and
unrelated errors, and has a few planted evidence lines and 2 or 3 decoy errors. Each incident
gets a `truth.json` with the 1-based line numbers of the evidence and the decoys.

Deterministic: the same seed writes the same bytes. Run from the repo root:

    python benchmarks/log_filter/gen_corpus.py            # write corpus/ and manifest.json
    python benchmarks/log_filter/gen_corpus.py --check    # regenerate in memory, compare hashes

No real system, company or person is described.
"""

