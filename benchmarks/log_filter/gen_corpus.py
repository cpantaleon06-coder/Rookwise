def _E(level: str, logger: str, msg: str, host: str | None = None, **fields) -> Event:
    return Event(level, logger, msg, fields, host)


@dataclass
class Planted:
    pos: float  # relative position in the log, 0..1
    event: Event
    note: str


@dataclass
class Incident:
    incident_id: str
    split: str
    fmt: str  # "text" or "jsonl"
    n_lines: int
    start: str
    root_cause: str
    evidence: list[Planted]
    decoys: list[Planted]
    debug_after: float | None = None  # relative position after which DEBUG noise appears


