def _fmt_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    return str(v)


def render(fmt: str, ts: datetime, ev: Event, host: str) -> str:
    stamp = ts.strftime("%Y-%m-%dT%H:%M:%S.") + f"{ts.microsecond // 1000:03d}Z"
    if fmt == "text":
        kv = " ".join(f"{k}={_fmt_value(v)}" for k, v in ev.fields.items())
        return f"{stamp} {ev.level:<5} {SERVICE}[{host}] {ev.logger}: {ev.msg}" + (
            f" {kv}" if kv else ""
        )
    obj = {
        "ts": stamp,
        "level": ev.level,
        "service": SERVICE,
        "host": host,
        "logger": ev.logger,
        "msg": ev.msg,
        **ev.fields,
    }
    return json.dumps(obj, ensure_ascii=False)


def build(inc: Incident, seed: int) -> tuple[str, dict]:
    rng = random.Random(f"{seed}:{inc.incident_id}")
    noise = Noise(rng)
    n = inc.n_lines
    header = HEADER.format(seed=seed, svc=SERVICE)
    planted: dict[int, tuple[str, Planted]] = {}
    for kind, items in (("evidence", inc.evidence), ("decoy", inc.decoys)):
        for p in items:
            line = max(2, min(n, int(round(p.pos * n))))
            while line in planted:
                line += 1
            planted[line] = (kind, p)
    debug_from = int(inc.debug_after * n) if inc.debug_after is not None else None

    ts = datetime.fromisoformat(inc.start).replace(tzinfo=UTC)
    mean_gap = 6 * 3600 / n  # about six hours per log
    lines = [header if inc.fmt == "text" else json.dumps({"synthetic": header})]
    truth_ev, truth_dec = [], []
    for no in range(2, n + 1):
        ts += timedelta(seconds=rng.expovariate(1 / mean_gap))
        noise.debug = debug_from is not None and no > debug_from
        if no in planted:
            kind, p = planted[no]
            ev = p.event
            text = render(inc.fmt, ts, ev, ev.host or rng.choice(HOSTS))
            entry = {"line": no, "text": text, "note": p.note}
            (truth_ev if kind == "evidence" else truth_dec).append(entry)
        else:
            ev = noise.next()
            text = render(inc.fmt, ts, ev, ev.host or rng.choice(HOSTS))
        lines.append(text)
    body = "\n".join(lines) + "\n"
    truth = {
        "synthetic": True,
        "note": "SYNTHETIC incident; the service and every event are made up.",
        "incident_id": inc.incident_id,
        "split": inc.split,
        "format": inc.fmt,
        "file": log_name(inc),
        "n_lines": n,
        "seed": seed,
        "root_cause": inc.root_cause,
        "evidence": truth_ev,
        "decoys": truth_dec,
    }
    return body, truth


def log_name(inc: Incident) -> str:
    return f"{inc.incident_id}.synthetic.{'txt' if inc.fmt == 'text' else 'jsonl'}"


def _check_truth(inc: Incident, body: str, truth: dict) -> None:
    lines = body.split("\n")
    assert len(lines) - 1 == inc.n_lines, inc.incident_id
    for e in truth["evidence"] + truth["decoys"]:
        assert lines[e["line"] - 1] == e["text"], (inc.incident_id, e["line"])
    assert 3 <= len(truth["evidence"]) <= 8 and 2 <= len(truth["decoys"]) <= 3
    assert 5000 <= inc.n_lines <= 20000


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare with corpus/manifest.json")
    args = ap.parse_args()
    manifest = {"synthetic": True, "seed": SEED, "files": {}}
    for inc in INCIDENTS:
        body, truth = build(inc, SEED)
        _check_truth(inc, body, truth)
        data = body.encode("utf-8")
        manifest["files"][f"{inc.incident_id}/{log_name(inc)}"] = {
            "sha256": hashlib.sha256(data).hexdigest(),
            "bytes": len(data),
            "lines": inc.n_lines,
        }
        if not args.check:
            d = OUT / inc.incident_id
            d.mkdir(parents=True, exist_ok=True)
            (d / log_name(inc)).write_bytes(data)
            (d / "truth.json").write_text(json.dumps(truth, indent=2) + "\n", encoding="utf-8")
    path = OUT / "manifest.json"
    if args.check:
        saved = json.loads(path.read_text(encoding="utf-8"))
        if saved != manifest:
            print("corpus differs from manifest.json", file=sys.stderr)
            return 1
        print("corpus matches manifest.json")
        return 0
    path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    for name, meta in manifest["files"].items():
        print(f"{name}: {meta['lines']} lines, {meta['bytes']} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
